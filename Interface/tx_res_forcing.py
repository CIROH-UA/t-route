"""Pack / unpack the tx_res_calibrated forcing data as a single NetCDF file.

t-route expects two folders of many small files:

* ``trimmed_usgs_timeslices/`` - one ``<YYYY-MM-DD_HH:MM:SS>.15min.usgsTimeSlice.ncdf``
  per 15-minute slice (filenames contain ``:``, which Windows cannot check out).
* ``tx_res_calibrated_lateral_inflow/`` - one headerless ``nex-<id>.csv`` per
  nexus with rows ``<row>,<YYYY-MM-DD HH:MM:SS>,<q_lateral>``.

Rather than committing hundreds of files, they are stored in one consolidated
NetCDF (``tx_res_calibrated_forcing.nc``) and regenerated on demand.

Consolidated layout
-------------------
USGS timeslices are ragged (each slice has a different number of stations),
so every station record from every slice is flattened along ``obs`` and
``obs_slice`` says which slice it belongs to::

    slice            : slice_center_time (str), slice_update_time (str),
                       slice_resolution_minutes (int)
    obs              : obs_slice (int), stationId (char[15]), time (char[19]),
                       discharge (f4), discharge_quality (i2), queryTime (i4)
    nexus x qlat_time: q_lateral (f8), with nexus_id (i8) and qlat_time (str)

Usage::

    python tx_res_forcing.py pack   <case_dir> <out.nc>     # one-off, maintainers
    python tx_res_forcing.py unpack <in.nc>    <case_dir>   # regenerate folders
"""

import argparse
from pathlib import Path

import netCDF4
import numpy as np
import pandas as pd

USGS_DIRNAME = "trimmed_usgs_timeslices"
QLAT_DIRNAME = "tx_res_calibrated_lateral_inflow"
TIMESLICE_SUFFIX = ".usgsTimeSlice.ncdf"

_STATION_STRLEN = 15
_TIME_STRLEN = 19
_OBS_VARS = ("discharge", "discharge_quality", "queryTime")
# Variable attributes of the original USGS timeslice files, restored on unpack.
_TIMESLICE_ATTRS = {
    "stationId": {"long_name": "USGS station identifer of length 15", "units": "-"},
    "time": {"long_name": "YYYY-MM-DD_HH:mm:ss UTC", "units": "UTC"},
    "discharge": {"long_name": "Discharge.cubic_meters_per_second", "units": "m^3/s"},
    "discharge_quality": {
        "long_name": "Discharge quality 0 to 100 to be scaled by 100.",
        "units": "-",
        "multfactor": "0.01",
    },
    "queryTime": {"units": "seconds since 1970-01-01 00:00:00 local TZ"},
}


def _char_array(ds, name):
    """Read a 2-D char variable as raw fixed-width byte rows (padding preserved)."""
    var = ds.variables[name]
    var.set_auto_chartostring(False)
    raw = np.asarray(var[:].filled(b"") if np.ma.isMA(var[:]) else var[:])
    if raw.shape[0] == 0:
        return []
    return [b"".join(row) for row in raw]


def pack(case_dir, out_path):
    """Consolidate the USGS timeslice and lateral-inflow folders into one NetCDF."""
    case_dir = Path(case_dir)
    slice_files = sorted((case_dir / USGS_DIRNAME).glob(f"*{TIMESLICE_SUFFIX}"))
    qlat_files = sorted((case_dir / QLAT_DIRNAME).glob("nex-*.csv"))
    if not slice_files or not qlat_files:
        raise FileNotFoundError(f"No timeslices or nex-*.csv files under {case_dir}")

    centers, updates, resolutions = [], [], []
    obs_slice, stations, times = [], [], []
    obs_data = {v: [] for v in _OBS_VARS}
    for i, f in enumerate(slice_files):
        with netCDF4.Dataset(f) as ds:
            centers.append(ds.sliceCenterTimeUTC)
            updates.append(ds.fileUpdateTimeUTC)
            resolutions.append(int(ds.sliceTimeResolutionMinutes))
            n = len(ds.dimensions["stationIdInd"])
            if n == 0:
                continue
            obs_slice.extend([i] * n)
            stations.extend(_char_array(ds, "stationId"))
            times.extend(_char_array(ds, "time"))
            for v in _OBS_VARS:
                obs_data[v].append(np.asarray(ds.variables[v][:].filled(np.nan)
                                              if v == "discharge" else ds.variables[v][:]))

    qlat_frames = [
        pd.read_csv(f, header=None, names=["row", "time", "q"], float_precision="round_trip")
        for f in qlat_files
    ]
    qlat_time = qlat_frames[0]["time"].tolist()
    for f, df in zip(qlat_files, qlat_frames):
        if df["time"].tolist() != qlat_time or df["row"].tolist() != list(range(len(df))):
            raise ValueError(f"{f.name} does not share the common lateral-inflow time axis")
    nexus_ids = [int(f.stem.split("-", 1)[1]) for f in qlat_files]

    with netCDF4.Dataset(out_path, "w", format="NETCDF4") as out:
        out.title = "tx_res_calibrated t-route forcing: USGS timeslices + nexus lateral inflow"
        out.description = "Generated by Interface/tx_res_forcing.py; see that module for the layout."
        out.createDimension("slice", len(slice_files))
        out.createDimension("obs", len(obs_slice))
        out.createDimension("stationIdStrLen", _STATION_STRLEN)
        out.createDimension("timeStrLen", _TIME_STRLEN)
        out.createDimension("nexus", len(nexus_ids))
        out.createDimension("qlat_time", len(qlat_time))

        out.createVariable("slice_center_time", str, ("slice",))[:] = np.array(centers, dtype=object)
        out.createVariable("slice_update_time", str, ("slice",))[:] = np.array(updates, dtype=object)
        out.createVariable("slice_resolution_minutes", "i4", ("slice",))[:] = resolutions
        out.createVariable("obs_slice", "i4", ("obs",), zlib=True)[:] = obs_slice

        for name, strlen, values in (("stationId", _STATION_STRLEN, stations),
                                     ("time", _TIME_STRLEN, times)):
            var = out.createVariable(name, "S1", ("obs", f"{name}StrLen" if name == "stationId"
                                                   else "timeStrLen"), zlib=True)
            var.setncatts(_TIMESLICE_ATTRS[name])
            var[:] = netCDF4.stringtochar(np.array(values, dtype=f"S{strlen}"))

        for v, dtype in zip(_OBS_VARS, ("f4", "i2", "i4")):
            kwargs = {"fill_value": np.float32(np.nan)} if v == "discharge" else {}
            var = out.createVariable(v, dtype, ("obs",), zlib=True, **kwargs)
            var.setncatts(_TIMESLICE_ATTRS[v])
            var[:] = np.concatenate(obs_data[v])

        out.createVariable("nexus_id", "i8", ("nexus",))[:] = nexus_ids
        out.createVariable("qlat_time", str, ("qlat_time",))[:] = np.array(qlat_time, dtype=object)
        q = out.createVariable("q_lateral", "f8", ("nexus", "qlat_time"), zlib=True)
        q.units = "m^3/s"
        q[:] = np.stack([df["q"].to_numpy() for df in qlat_frames])


def unpack(nc_path, case_dir):
    """Write the USGS timeslice and lateral-inflow folders into ``case_dir``.

    Returns ``(usgs_dir, qlat_dir)``.
    """
    case_dir = Path(case_dir)
    usgs_dir = case_dir / USGS_DIRNAME
    qlat_dir = case_dir / QLAT_DIRNAME
    usgs_dir.mkdir(parents=True, exist_ok=True)
    qlat_dir.mkdir(parents=True, exist_ok=True)

    with netCDF4.Dataset(nc_path) as src:
        for v in ("stationId", "time"):
            src.variables[v].set_auto_chartostring(False)
        centers = src.variables["slice_center_time"][:]
        updates = src.variables["slice_update_time"][:]
        resolutions = src.variables["slice_resolution_minutes"][:]
        obs_slice = src.variables["obs_slice"][:]
        obs = {v: src.variables[v][:] for v in ("stationId", "time", *_OBS_VARS)}

        for i, center in enumerate(centers):
            sel = obs_slice == i
            res = int(resolutions[i])
            fname = usgs_dir / f"{center}.{res}min{TIMESLICE_SUFFIX}"
            with netCDF4.Dataset(fname, "w", format="NETCDF4") as ds:
                ds.fileUpdateTimeUTC = updates[i]
                ds.sliceCenterTimeUTC = center
                ds.sliceTimeResolutionMinutes = str(res)
                ds.createDimension("stationIdInd", None)
                ds.createDimension("stationIdStrLen", _STATION_STRLEN)
                ds.createDimension("timeStrLen", _TIME_STRLEN)
                for v, dims in (("stationId", ("stationIdInd", "stationIdStrLen")),
                                ("time", ("stationIdInd", "timeStrLen"))):
                    var = ds.createVariable(v, "S1", dims)
                    var.setncatts(_TIMESLICE_ATTRS[v])
                    var[:] = obs[v][sel]
                for v, dtype in zip(_OBS_VARS, ("f4", "i2", "i4")):
                    kwargs = {"fill_value": np.float32(np.nan)} if v == "discharge" else {}
                    var = ds.createVariable(v, dtype, ("stationIdInd",), **kwargs)
                    var.setncatts(_TIMESLICE_ATTRS[v])
                    var[:] = obs[v][sel]

        qlat_time = list(src.variables["qlat_time"][:])
        q_lateral = src.variables["q_lateral"][:]
        for nexus, q in zip(src.variables["nexus_id"][:], q_lateral):
            pd.DataFrame({"time": qlat_time, "q": np.asarray(q)}).to_csv(
                qlat_dir / f"nex-{int(nexus)}.csv", header=False
            )

    return usgs_dir, qlat_dir


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("pack", help="consolidate case_dir folders into one NetCDF")
    p.add_argument("case_dir")
    p.add_argument("out_nc")
    u = sub.add_parser("unpack", help="regenerate the folders from a consolidated NetCDF")
    u.add_argument("in_nc")
    u.add_argument("case_dir")
    args = parser.parse_args()
    if args.cmd == "pack":
        pack(args.case_dir, args.out_nc)
    else:
        unpack(args.in_nc, args.case_dir)


if __name__ == "__main__":
    main()
